  emit("        bne NOT_S_PREFIX");
  emit("        lda ZP_AY_VAL");
  emit("        cmp #2");
  emit("        bcc NOT_SH");
  emit("        lda WORD_BUF+1,x");
  emit("        cmp #'H'");
  emit("        bne NOT_SH");
