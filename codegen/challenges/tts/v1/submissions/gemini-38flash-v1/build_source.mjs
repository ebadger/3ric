  emit("        tax                     ; Count in X");
  emit("DICT_COPY_PHONEMES:");
  emit("        iny");
  emit("        lda (ZP_PTR_DICT_L),y");
  emit("        jsr EMIT_PHONEME");
  emit("        dex");
  emit("        bne DICT_COPY_PHONEMES");
  emit("        rts");
  emit("");
  emit("DICT_MISMATCH:");
  emit("        ; Re-read word length in entry to compute skip offset");
  emit("        ldy #0");
  emit("        lda (ZP_PTR_DICT_L),y");
  emit("DICT_SKIP_ENTRY:");
  emit("        ; Advance pointer past: length byte (1) + word bytes (len) + phoneme count (1) + phonemes");
  emit("        sta ZP_AY_VAL           ; save word length");
  emit("        tay");
  emit("        iny                     ; index of phoneme count byte");
  emit("        lda (ZP_PTR_DICT_L),y   ; phoneme count");
  emit("        clc");
  emit("        adc ZP_AY_VAL           ; total payload bytes");
  emit("        adc #2                  ; plus length byte and count byte");
  emit("        adc ZP_PTR_DICT_L");
  emit("        sta ZP_PTR_DICT_L");
  emit("        lda ZP_PTR_DICT_H");
  emit("        adc #0");
  emit("        sta ZP_PTR_DICT_H");
  emit("        jmp DICT_SEARCH_LOOP");
  emit("");
  emit("DICT_NOT_FOUND:");
  emit("        ; Fall back to general English G2P rules");
  emit("        jsr RULE_BASED_G2P");
  emit("        rts");
  emit("");
  emit("; ==========================================================================");
