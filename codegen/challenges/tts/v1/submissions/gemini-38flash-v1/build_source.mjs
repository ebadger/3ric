  emit("        sta WORD_BUF,x");
  emit("        inx");
  emit("        cpx #30             ; Limit word length to 30 chars");
  emit("        bcs WORD_COLLECTED");
  emit("        iny");
  emit("        lda (ZP_PTR_IN_L),y");
  emit("        beq WORD_COLLECTED");
  emit("        jsr IS_ALPHA");
  emit("        bcs COLLECT_WORD_LOOP");
  emit("");
  emit("WORD_COLLECTED:");
  emit("        stx ZP_WORD_LEN");
  emit("        phy                 ; Save input string index");
  emit("        jsr CONVERT_WORD");
  emit("        ply                 ; Restore input string index");
  emit("");
  emit("        ; Emit word pause");
  emit("        lda #P_PAUSE_WORD");
  emit("        jsr EMIT_PHONEME");
  emit("");
  emit("        ; Continue parsing");
  emit("        jmp PARSE_MAIN_LOOP");
  emit("");
  emit("NOT_ALPHA_CHAR:");
