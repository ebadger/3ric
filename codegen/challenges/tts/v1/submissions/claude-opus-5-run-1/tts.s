; =====================================================================
; Type-and-speak front end.
;   RETURN  speaks the line          ESC (speaking) cancels
;   DELETE  erases a character       ESC (prompt)   returns to the
;   120 characters maximum                          monitor with BRK
; =====================================================================
UIMAIN:
        cld
        jsr TTS_INIT
        lda #<msg_banner
        ldx #>msg_banner
        jsr puts
ui_loop:
        jsr readline
        bcs ui_exit
        lda uilen
        beq ui_loop
        lda #<TTS_INPUT
        ldx #>TTS_INPUT
        jsr TTS_SPEAK
        cmp #1
        beq ui_cancel
        cmp #2
        beq ui_bad
        bra ui_loop
ui_cancel:
        lda #<msg_cancel
        ldx #>msg_cancel
        jsr puts
        bra ui_loop
ui_bad:
        lda #<msg_bad
        ldx #>msg_bad
        jsr puts
        bra ui_loop
ui_exit:
        lda #<msg_bye
        ldx #>msg_bye
        jsr puts
        brk

; readline -- fill TTS_INPUT.  C = 1 when Escape was pressed.
readline:
        lda #0
        sta uilen
        sta TTS_INPUT
        lda #<msg_prompt
        ldx #>msg_prompt
        jsr puts
rl_key:
        jsr getkey
        cmp #$0D
        beq rl_done
        cmp #$1B
        beq rl_esc
        cmp #$08
        beq rl_del
        cmp #$7F
        beq rl_del
        cmp #$20
        bcc rl_key
        cmp #$7B
        bcs rl_key
        cmp #$61
        bcc rl_nolow
        sec
        sbc #32
rl_nolow:
        sta uitmp
        ldx uilen
        cpx #120
        bcs rl_full
        sta TTS_INPUT,x
        inx
        stx uilen
        lda #0
        sta TTS_INPUT,x
        lda uitmp
        ora #$80
        jsr COUT
        bra rl_key
rl_full:
        lda #$87                ; the line is full: beep
        jsr COUT
        bra rl_key
rl_del:
        ldx uilen
        beq rl_key
        dex
        stx uilen
        lda #0
        sta TTS_INPUT,x
        lda #$88
        jsr COUT
        lda #$A0
        jsr COUT
        lda #$88
        jsr COUT
        bra rl_key
rl_done:
        jsr crout
        clc
        rts
rl_esc:
        jsr crout
        sec
        rts

getkey:
        lda KBD
        bpl getkey
        bit KBDSTRB
        and #$7F
        rts

crout:
        lda #$8D
        jmp COUT

; puts -- print the NUL-terminated string at A/X, adding the high bit.
puts:
        sta ZSRC
        stx ZSRC+1
        ldy #0
pu_loop:
        lda (ZSRC),y
        beq pu_done
        ora #$80
        jsr COUT
        iny
        bne pu_loop
pu_done:
        rts

