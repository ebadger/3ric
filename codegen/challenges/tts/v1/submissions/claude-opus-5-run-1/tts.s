; ---------------------------------------------------------------------
; TTS_INIT -- reset both 6522/AY pairs and leave the machine silent.
; Clobbers A, X, Y.
; ---------------------------------------------------------------------
TTS_INIT:
        jsr savezp
        lda #$7F
        sta MB0+V_IER           ; no VIA interrupts from either chip
        sta MB1+V_IER
        sta MB0+V_IFR
        sta MB1+V_IFR
        lda #0
        sta MB0+V_ACR
        sta MB1+V_ACR
        sta MB0+V_ORB           ; AY reset low
        sta MB1+V_ORB
        lda #$FF
        sta MB0+V_DDRA
        sta MB1+V_DDRA
        lda #$07
        sta MB0+V_DDRB
        sta MB1+V_DDRB
        lda #0
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda #4                  ; release reset, bus inactive
        sta MB0+V_ORB
        sta MB1+V_ORB
        jsr silence
        lda #$3F                ; mixer: every tone and noise source off
        ldx #7
        jsr aywrite
        lda #$40                ; T1 free run, no PB7 output
        sta MB0+V_ACR
        sta MB1+V_ACR
        jsr restzp
        lda #0
        rts

; silence -- amplitudes of A, B and C to zero on both chips.
silence:
        lda #0
        ldx #8
        jsr aywrite
        lda #0
        ldx #9
        jsr aywrite
        lda #0
        ldx #10
        jsr aywrite
        rts

; aywrite -- A = data, X = AY register; written to both chips.
aywrite:
        sta ayval
        stx MB0+V_ORA
        stx MB1+V_ORA
        lda #7                  ; latch address
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda #4
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda ayval
        sta MB0+V_ORA
        sta MB1+V_ORA
        lda #6                  ; write data
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda #4
        sta MB0+V_ORB
        sta MB1+V_ORB
        rts

savezp:
        ldx #28
sz1:    lda $06,x
        sta zpsave,x
        dex
        bpl sz1
        rts

restzp:
        ldx #28
rz1:    lda zpsave,x
        sta $06,x
        dex
        bpl rz1
        rts

; ---------------------------------------------------------------------
; TTS_SPEAK -- speak the NUL-terminated ASCII string whose address is
; in A (low) / X (high).
;   Returns A = 0 spoken to completion
;           A = 1 cancelled by Escape
;           A = 2 invalid or over-length input (nothing is spoken)
; Clobbers A, X, Y and zero page $06-$1F (saved and restored).
; The caller's string is never modified.
; ---------------------------------------------------------------------
TTS_SPEAK:
        sta ptrlo
        stx ptrhi
        jsr savezp
        lda #2
        sta result
        jsr normalize
        bcs spk_out             ; invalid -> A = 2
        jsr translate
        lda #0
        sta result
        lda phonlen
        beq spk_out             ; nothing to say, still success
        jsr expand
        jsr speak
        lda cancel
        beq spk_out
        lda #1
        sta result
spk_out:
        jsr restzp
        lda result
        rts

; ---------------------------------------------------------------------
; TTS_TRANSLATE -- extension beyond the required ABI.  Runs the text
; through validation and the letter-to-sound rules without speaking,
; leaving the phoneme string in phonbuf.  A/X = string pointer on
; entry; returns A = phoneme count (0 when the text is invalid or has
; nothing to say).  Used by test.mjs to check the rules quickly.
; ---------------------------------------------------------------------
TTS_TRANSLATE:
        sta ptrlo
        stx ptrhi
        jsr savezp
        lda #0
        sta phonlen
        jsr normalize
        bcs ttr_out
        jsr translate
ttr_out:
        jsr restzp
        lda phonlen
        rts

; ---------------------------------------------------------------------
; normalize -- copy the caller's text into normbuf, fold to upper case,
; validate it and reject anything longer than 120 characters.
; Returns C = 1 when the text is invalid.
; ---------------------------------------------------------------------
normalize:
        lda ptrlo
        sta ZSRC
        lda ptrhi
        sta ZSRC+1
        ldy #0
nm_loop:
        lda (ZSRC),y
        beq nm_end
        cpy #120
        bcs nm_bad              ; a 121st character is over the limit
        cmp #$61                ; 'a'
        bcc nm_nolow
        cmp #$7B                ; 'z'+1
        bcs nm_nolow
        sec
        sbc #32
nm_nolow:
        cmp #$41                ; 'A'
        bcc nm_punct
        cmp #$5B                ; 'Z'+1
        bcc nm_store
nm_punct:
        cmp #$20                ; space
        beq nm_store
        cmp #$27                ; apostrophe
        beq nm_store
        cmp #$2E                ; .
        beq nm_store
        cmp #$2C                ; ,
        beq nm_store
        cmp #$3F                ; ?
        beq nm_period
        cmp #$21                ; !
        beq nm_period
        cmp #$3A                ; :
        beq nm_comma
        cmp #$3B                ; ;
        beq nm_comma
        cmp #$2D                ; - becomes a word break
        beq nm_space
        bra nm_bad
nm_period:
        lda #$2E
        bra nm_store
nm_comma:
        lda #$2C
        bra nm_store
nm_space:
        lda #$20
nm_store:
        sta normbuf,y
        iny
        bra nm_loop
nm_end:
        sty normlen
        lda #0
        sta normbuf,y
        clc
        rts
nm_bad:
        sec
        rts

; ---------------------------------------------------------------------
; translate -- normbuf -> phonbuf, using the exception list first and
; then the context-sensitive letter-to-sound rules.
; ---------------------------------------------------------------------
translate:
        lda #0
        sta phonlen
        sta tpos
tr_loop:
        ldy tpos
        cpy normlen
        bcs tr_done
        lda normbuf,y
        jsr isletter
        bcs tr_word
        cmp #$2C                ; ,
        beq tr_punct
        cmp #$2E                ; .
        beq tr_punct
        lda #$20                ; anything else is a word gap
tr_punct:
        jsr emitgap
        inc tpos
        bra tr_loop
tr_word:
        jsr findword
        jsr exception
        bcs tr_next
        jsr wordrules
tr_next:
        lda wend
        sta tpos
        bra tr_loop
tr_done:
        lda #$2E                ; final settling pause
        jsr emitgap
        ldx #0
tr_scan:
        cpx phonlen
        bcs tr_none
        lda phonbuf,x
        cmp #$20
        beq tr_skip
        cmp #$2C
        beq tr_skip
        cmp #$2E
        bne tr_some
tr_skip:
        inx
        bra tr_scan
tr_none:
        lda #0                  ; nothing but pauses: say nothing at all
        sta phonlen
tr_some:
        rts

; emitgap -- append pause phoneme in A, collapsing runs of pauses and
; letting the stronger pause win.
emitgap:
        sta ZTMP
        ldx phonlen
        beq eg_emit
        dex
        lda phonbuf,x
        cmp #$20
        beq eg_repl
        cmp #$2C
        beq eg_repl
        cmp #$2E
        bne eg_emit
eg_repl:
        cmp ZTMP                ; keep the longer of the two pauses
        bcs eg_skip
        lda ZTMP
        sta phonbuf,x
eg_skip:
        rts
eg_emit:
        lda ZTMP
        jmp emit

; isletter -- C = 1 when A holds 'A'-'Z'.
isletter:
        cmp #$41
        bcc il_no
        cmp #$5B
        bcs il_no
        sec
        rts
il_no:
        clc
        rts

; isvowel -- C = 1 when A is one of A E I O U Y.
isvowel:
        cmp #$41
        beq iv_yes
        cmp #$45
        beq iv_yes
        cmp #$49
        beq iv_yes
        cmp #$4F
        beq iv_yes
        cmp #$55
        beq iv_yes
        cmp #$59
        beq iv_yes
        clc
        rts
iv_yes:
        sec
        rts

; findword -- wstart = tpos, wend = first index past the word.
findword:
        lda tpos
        sta wstart
        tay
fw_loop:
        cpy normlen
        bcs fw_end
        lda normbuf,y
        jsr isletter
        bcs fw_more
        cmp #$27                ; apostrophe inside a word
        bne fw_end
fw_more:
        iny
        bra fw_loop
fw_end:
        sty wend
        rts

; emit -- append phoneme code A to phonbuf.
emit:
        ldx phonlen
        cpx #PHONMAX
        bcs em_full
        sta phonbuf,x
        inc phonlen
em_full:
        rts

; ---------------------------------------------------------------------
; exception -- look the whole word up in exctab.  C = 1 when found and
; its phonemes have been emitted.
; ---------------------------------------------------------------------
exception:
        lda #<exctab
        sta ZE
        lda #>exctab
        sta ZE+1
ex_entry:
        ldy #0
        lda (ZE),y
        beq ex_no
        ldx wstart
ex_cmp:
        lda (ZE),y
        beq ex_wend
        cpx wend
        bcs ex_skip
        cmp normbuf,x
        bne ex_skip
        inx
        iny
        bra ex_cmp
ex_wend:
        cpx wend
        bne ex_skip
        iny
ex_emit:
        lda (ZE),y
        beq ex_yes
        jsr emit
        iny
        bra ex_emit
ex_yes:
        sec
        rts
ex_skip:
        jsr skipstr
        jsr skipstr
        bra ex_entry
ex_no:
        clc
        rts

; skipstr -- advance ZE past one NUL-terminated string.
skipstr:
        ldy #0
ss_loop:
        lda (ZE),y
        beq ss_end
        iny
        bra ss_loop
ss_end:
        iny
        tya
        clc
        adc ZE
        sta ZE
        bcc ss_out
        inc ZE+1
ss_out:
        rts

; ---------------------------------------------------------------------
; wordrules -- walk the word left to right, applying the first matching
; rule for the letter under the cursor.
; ---------------------------------------------------------------------
wordrules:
        lda wstart
        sta tpos
wr_loop:
        lda tpos
        cmp wend
        bcs wr_done
        jsr onerule
        bra wr_loop
wr_done:
        rts

onerule:
        ldy tpos
        lda normbuf,y
        cmp #$27                ; apostrophe has its own group
        beq or_apos
        sec
        sbc #$41
        cmp #26
        bcc or_group
or_apos:
        lda #26
or_group:
        asl a
        tax
        lda ruleidx,x
        sta ZR
        lda ruleidx+1,x
        sta ZR+1
or_try:
        ldy #0
        lda (ZR),y
        beq or_fail
        jsr matchrule
        bcs or_hit
        jsr nextrule
        bra or_try
or_fail:
        inc tpos                ; no rule at all: skip the letter
or_hit:
        rts

; nextrule -- advance ZR past the current rule.
nextrule:
        ldy #0
nr_loop:
        lda (ZR),y
        beq nr_end
        iny
        bra nr_loop
nr_end:
        iny
        tya
        clc
        adc ZR
        sta ZR
        bcc nr_out
        inc ZR+1
nr_out:
        rts

; ---------------------------------------------------------------------
; matchrule -- try the rule at ZR against the text at tpos.
; A rule is  LEFT ( FOCUS ) RIGHT = PHONEMES <NUL>  where the context
; patterns may use  # vowel  @ consonant  + front vowel  . any letter
; < word start  > word end.  On success the phonemes are emitted and
; tpos is advanced past the focus; C = 1.
; ---------------------------------------------------------------------
matchrule:
        ldy #$FF
mr_findl:
        iny
        lda (ZR),y
        cmp #$28                ; (
        bne mr_findl
        sty lpar
        ldx tpos
mr_focus:
        iny
        lda (ZR),y
        cmp #$29                ; )
        beq mr_fdone
        cpx wend
        bcs mr_no
        cmp normbuf,x
        bne mr_no
        inx
        bra mr_focus
mr_fdone:
        stx focend
mr_right:
        iny
        lda (ZR),y
        cmp #$3D                ; =
        beq mr_rdone
        cmp #$3E                ; > word end
        bne mr_rclass
        cpx wend
        bne mr_no
        bra mr_right
mr_rclass:
        cpx wend
        bcs mr_no
        jsr classmatch
        bcc mr_no
        inx
        bra mr_right
mr_rdone:
        sty outoff
        ldy lpar
        ldx tpos
mr_left:
        dey
        bmi mr_yes
        lda (ZR),y
        cmp #$3C                ; < word start
        bne mr_lclass
        cpx wstart
        bne mr_no
        bra mr_left
mr_lclass:
        cpx wstart
        beq mr_no
        dex
        jsr classmatch
        bcc mr_no
        bra mr_left
mr_yes:
        ldy outoff
mr_emit:
        iny
        lda (ZR),y
        beq mr_edone
        jsr emit
        bra mr_emit
mr_edone:
        lda focend
        sta tpos
        sec
        rts
mr_no:
        clc
        rts

; classmatch -- A = pattern byte, X = index into normbuf.  C = 1 match.
classmatch:
        cmp #$23                ; #
        beq cm_vowel
        cmp #$40                ; @
        beq cm_cons
        cmp #$2B                ; +
        beq cm_front
        cmp #$2E                ; .
        beq cm_any
        cmp normbuf,x
        beq cm_yes
        clc
        rts
cm_vowel:
        lda normbuf,x
        jmp isvowel
cm_cons:
        lda normbuf,x
        jsr isletter
        bcc cm_no
        lda normbuf,x
        jsr isvowel
        bcc cm_yes
        clc
        rts
cm_front:
        lda normbuf,x
        cmp #$45                ; E
        beq cm_yes
        cmp #$49                ; I
        beq cm_yes
        cmp #$59                ; Y
        beq cm_yes
        clc
        rts
cm_any:
        lda normbuf,x
        jmp isletter
cm_yes:
        sec
        rts
cm_no:
        clc
        rts

; ---------------------------------------------------------------------
; expand -- phonbuf (phoneme codes) -> recbuf (synthesis records),
; following the link chains that turn diphthongs, affricates and stops
; into their component segments.
; ---------------------------------------------------------------------
expand:
        lda #0
        sta reclen
        sta phidx
ex2_loop:
        ldy phidx
        cpy phonlen
        bcs ex2_done
        inc phidx
        lda phonbuf,y
        jsr findrec
        bcc ex2_loop
ex2_chain:
        ldx reclen
        cpx #RECMAX
        bcs ex2_done
        sta recbuf,x
        inc reclen
        tax
        lda rec_link,x
        bne ex2_chain
        bra ex2_loop
ex2_done:
        rts

; findrec -- phoneme code in A -> record index in A, C = 1 when known.
findrec:
        ldx #0
fr_loop:
        ldy pho_map,x
        beq fr_no
        cmp pho_map,x
        beq fr_hit
        inx
        inx
        bra fr_loop
fr_hit:
        lda pho_map+1,x
        sec
        rts
fr_no:
        clc
        rts

; ---------------------------------------------------------------------
; speak -- render recbuf through the Mockingboards.
; ---------------------------------------------------------------------
speak:
        lda #0
        sta cancel
        sta release
        sta declin
        sta recidx
        sta ZPC
        sta ZTSK
        lda #T0BASE
        sta ZT0
        lda #104                ; start at a quiet neutral vocal tract
        sta ZCU1
        sta tf1
        lda #144
        sta ZCU2
        sta tf2
        lda #40
        sta ZCU3
        sta tf3
        lda #0
        sta ZCUA
        sta tav
        lda #1
        sta frames              ; force a record load on the first frame
        lda #FRAMELEN
        sta ZFRM
        stz nmode
        stz noiseamp
        jsr setptrs
        lda #$40                ; free-running sample clock
        sta MB0+V_ACR
        sta MB1+V_ACR
        lda #<(SMPPER-1)
        sta MB0+V_T1CL
        lda #>(SMPPER-1)
        sta MB0+V_T1CH          ; start the free-running sample clock

; --- the sample loop -------------------------------------------------
sample:
        ldy ZPC
        lda (ZF1),y
        clc
        adc (ZF2),y
        clc
        adc (ZF3),y
        tay                     ; the DAC tables are indexed by the signed sum
        lda (ZGA),y
        sta ZCA
        lda (ZGB),y
        sta ZCB
        lda (ZGC),y
        tax
sl_wait:
        bit MB0+V_IFR
        bvc sl_wait
        bit MB0+V_T1CL
        lda #8                  ; channel A amplitude
        sta MB0+V_ORA
        sta MB1+V_ORA
        lda #7
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda #4
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda ZCA
        sta MB0+V_ORA
        sta MB1+V_ORA
        lda #6
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda #4
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda #9                  ; channel B amplitude
        sta MB0+V_ORA
        sta MB1+V_ORA
        lda #7
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda #4
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda ZCB
        sta MB0+V_ORA
        sta MB1+V_ORA
        lda #6
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda #4
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda #10                 ; channel C amplitude
        sta MB0+V_ORA
        sta MB1+V_ORA
        lda #7
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda #4
        sta MB0+V_ORB
        sta MB1+V_ORB
        txa
        sta MB0+V_ORA
        sta MB1+V_ORA
        lda #6
        sta MB0+V_ORB
        sta MB1+V_ORB
        lda #4
        sta MB0+V_ORB
        sta MB1+V_ORB
        inc ZPC                 ; next sample of the glottal period
        lda ZT0
        cmp ZPC
        bcs sl_frame
        stz ZPC
sl_frame:
        dec ZFRM
        bne sl_task
        lda #FRAMELEN
        sta ZFRM
        stz ZTSK                ; start a new round of control tasks
sl_task:
        ldx ZTSK
        bpl sl_run
        jmp sample
sl_run:
        lda ZTSK
        clc
        adc #2
        cmp #TASKEND
        bcc sl_store
        lda #$FF
sl_store:
        sta ZTSK
        jmp (tasktab,x)

; --- per-frame control tasks, one per sample -------------------------
; task 0: advance the record timeline
t_adv:
        dec frames
        bne ta_skip
        jmp ta_next
ta_skip:
        jmp sample
ta_next:
        ldy recidx
        cpy reclen
        bcc ta_go
        jmp ta_end
ta_go:
        inc recidx
        lda recbuf,y
        tax
        lda rec_f1,x
        sta tf1
        lda rec_f2,x
        sta tf2
        lda rec_f3,x
        sta tf3
        lda rec_av,x
        sta tav
        lda rec_dur,x
        sta frames
        lda rec_flag,x
        lsr a
        bcc ta_nojump
        lda tf1                 ; bit 0: jump straight to the target
        sta ZCU1
        lda tf2
        sta ZCU2
        lda tf3
        sta ZCU3
        lda tav
        sta ZCUA
        jsr setptrs
ta_nojump:
        lda rec_flag,x
        and #2
        beq ta_nopitch
        lda #T0BASE             ; bit 1: a pause resets the pitch
        sta ZT0
        stz declin
ta_nopitch:
        stx ZTMP                ; keep the record index across aywrite
        lda rec_np,x
        beq ta_noper            ; period 0: leave the noise pitch alone
        ldx #6
        jsr aywrite
ta_noper:
        ldx ZTMP
        lda rec_an,x            ; noise amplitude decides which DAC mode
        sta noiseamp
        beq ta_dacmode
        lda #1
        sta nmode
        lda #$2F                ; tones off, noise on channel B only
        ldx #7
        jsr aywrite
        bra ta_mode
ta_dacmode:
        stz nmode
        lda #$3F                ; tones and noise off: A+B+C are the DAC
        ldx #7
        jsr aywrite
ta_mode:
        jsr setptrs
        ldx ZTMP
        lda rec_av,x
        beq ta_novoice
        inc declin              ; gentle declination over the phrase
        lda declin
        and #1
        bne ta_novoice
        lda ZT0
        cmp #T0MAX
        bcs ta_novoice
        inc ZT0
ta_novoice:
        jmp sample
; task 1: smooth formant 1
t_sf1:
