        lsr a
        lsr a
        lsr a
        tax
        lda f2_lo,x
        sta ZF2
        lda f2_hi,x
        sta ZF2+1
        jmp sample
; task 5: smooth formant 3
t_sf3:
        lda tf3
        sec
        sbc ZCU3
        cmp #$80
        ror a
        clc
        adc ZCU3
        sta ZCU3
        jmp sample
; task 6
t_pf3:
        lda ZCU3
        lsr a
        lsr a
        lsr a
        tax
        lda f3_lo,x
        sta ZF3
        lda f3_hi,x
        sta ZF3+1
