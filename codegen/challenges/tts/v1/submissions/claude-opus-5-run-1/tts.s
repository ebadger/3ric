; task 10: channel-B code table.  In noise mode channel B carries the
; AY noise generator, so its "table" is a constant page holding the
; record's noise amplitude; otherwise it is the third DAC channel.
t_pgb:
        lda nmode
        bne tpb_noise
        lda ZCUA
        lsr a
        lsr a
        lsr a
        tax
        lda gainb3_lo,x
        sta ZGB
        lda gainb3_hi,x
        sta ZGB+1
        jmp sample
tpb_noise:
        ldx noiseamp
        lda nconst_lo,x
        sta ZGB
        lda nconst_hi,x
        sta ZGB+1
        jmp sample
; task 11: watch for Escape
t_key:
        lda KBD
        bpl tk_out
        and #$7F
        cmp #$1B
        bne tk_out
        bit KBDSTRB
        inc cancel
        jmp spk_stop
tk_out:
        jmp sample

ta_end:
        lda release
        bne spk_stop
        inc release
        lda #0                  ; fade out, then settle in silence
        sta tav
        lda #8
        sta frames
        jmp sample

