; =====================================================================
; 3RIC TALKS v1 -- entry "claude-opus-5-run-1"
; An original parallel-formant English text-to-speech engine for the
; 3RIC 65C02 machine.  All speech is produced by writing AY-3-8910
; registers on the two Mockingboard chips at $C400 / $C480.
;
;   * The AY amplitude registers of channels A and C are used together
;     as a summed logarithmic DAC (~136 distinct levels, ~29 dB SNR).
;     Both chips receive identical data, so the machine speaks in mono
;     out of both outputs.
;   * Channel B of each chip runs the AY's own hardware noise generator
;     and supplies fricatives, aspiration and stop bursts.
;   * Everything that depends on the text -- letter-to-sound rules,
;     phoneme timing, formant trajectories and the sample-by-sample
;     waveform -- is computed on the 65C02 at native speed.
;
; See README.md for the ABI, memory map, timing and limitations.
; =====================================================================

