export function buildFont() {
  const out = new Uint8Array(1024);
  const put = (code, art) => {
    const rows = art.split("|");
    for (let r = 0; r < 8; r++) {
      let v = 0;
      for (let b = 0; b < 8; b++) if (rows[r][b] === "#") v |= 0x80 >> b;
      out[code * 8 + r] = v;
    }
  };
  for (let i = 0; i < 64; i++) put(i, G[String.fromCharCode(32 + i)]);
  for (let i = 0; i < 32; i++) put(64 + i, GRAPHICS[i % GRAPHICS.length]);
  for (let i = 0; i < 32; i++) { // lower case: small capitals one row lower
    const src = i === 0 ? " " : String.fromCharCode(64 + i);
    const g = G[src] || G[" "];
    put(96 + i, "........|" + g.split("|").slice(0, 7).join("|"));
  }
  return out;
}
